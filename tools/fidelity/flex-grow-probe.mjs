// Measures tools/fidelity/flex-grow-probe.html (fractional flex-grow
// without the panels port) in pinned Chromium and writes the boxes for
// tests/probe_layout.rs.
//
//     node tools/fidelity/flex-grow-probe.mjs CHROME OUTPUT

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { launch } from "./chromium.mjs";

const [chromePath, outputPath] = process.argv.slice(2);
if (!chromePath || !outputPath) {
  console.error("usage: node tools/fidelity/flex-grow-probe.mjs CHROME OUTPUT");
  process.exit(2);
}
const page = join(dirname(fileURLToPath(import.meta.url)), "flex-grow-probe.html");
const browser = await launch(chromePath, { width: 800, height: 400 });
let cases;
try {
  await browser.cdp.load(pathToFileURL(page).href);
  cases = JSON.parse(await browser.cdp.evaluate("document.getElementById('out').textContent"));
} finally {
  await browser.close();
}
const comment =
  "Generated by tools/fidelity/flex-grow-probe.mjs; do not edit. " +
  "Each case lists [offset, size] along the main axis for every child, separators included.";
const lines = Object.entries(cases).map(([id, boxes]) => `    ${JSON.stringify(id)}: ${JSON.stringify(boxes)}`);
writeFileSync(
  outputPath,
  [
    "{",
    `  "comment": ${JSON.stringify(comment)},`,
    `  "chromium": ${JSON.stringify(browser.version)},`,
    '  "cases": {',
    lines.join(",\n"),
    "  }",
    "}",
    "",
  ].join("\n"),
);
console.log(`${browser.version}: ${Object.keys(cases).length} cases`);
