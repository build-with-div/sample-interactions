// Replays tests/fixtures/fidelity/panels-scenarios.json against the
// react-resizable-panels reference page in pinned Chromium, over the
// DevTools protocol, and writes what the page shows after each step.
//
//     node tools/fidelity/capture.mjs CHROME OUTPUT
//
// CHROME is Chrome for Testing 147.0.7727.50, the build Div's census pins
// (tools/accountability). Build the page first (reference/build.mjs).
// tests/fidelity_panels.rs replays the same steps on Div and compares.
//
// Input arrives as trusted browser input (Input.dispatchMouseEvent and
// Input.dispatchKeyEvent), so Chromium produces the pointer, mouse and
// click events itself. The page settles after each step (two frames and a
// task).

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { launch } from "./chromium.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const [chromePath, outputPath] = process.argv.slice(2);
if (!chromePath || !outputPath) {
  console.error("usage: node tools/fidelity/capture.mjs CHROME OUTPUT");
  process.exit(2);
}
const spec = JSON.parse(
  readFileSync(join(root, "tests/fixtures/fidelity/panels-scenarios.json"), "utf8"),
);
const page = join(root, "out/reference/panels.html");
if (!existsSync(page)) {
  console.error(`${page} is missing: run node reference/build.mjs`);
  process.exit(2);
}
const generator = readFileSync(page, "utf8").match(/<meta name="generator" content="([^"]*)">/)[1];

// Windows virtual-key codes, which Chromium needs to produce the DOM key.
const KEYS = {
  ArrowLeft: 37,
  ArrowUp: 38,
  ArrowRight: 39,
  ArrowDown: 40,
  Home: 36,
  End: 35,
  Enter: 13,
  F6: 117,
};

async function step(cdp, entry, pressed) {
  if (entry.mouse) {
    const type = { move: "mouseMoved", down: "mousePressed", up: "mouseReleased" }[entry.mouse];
    if (entry.mouse === "down") pressed.left = true;
    if (entry.mouse === "up") pressed.left = false;
    let button = "left";
    if (entry.mouse === "move") button = pressed.left ? "left" : "none";
    await cdp.send("Input.dispatchMouseEvent", {
      type,
      x: entry.x,
      y: entry.y,
      button,
      buttons: pressed.left ? 1 : 0,
      clickCount: entry.mouse === "move" ? 0 : 1,
      pointerType: "mouse",
    });
  } else if (entry.key) {
    const code = KEYS[entry.key];
    if (!code) throw new Error(`unknown key ${entry.key}`);
    const key = {
      key: entry.key,
      code: entry.key,
      windowsVirtualKeyCode: code,
      nativeVirtualKeyCode: code,
      modifiers: entry.shift ? 8 : 0,
    };
    await cdp.send("Input.dispatchKeyEvent", { type: "rawKeyDown", ...key });
    await cdp.send("Input.dispatchKeyEvent", { type: "keyUp", ...key });
  } else if (entry.focus) {
    await cdp.evaluate(`document.getElementById(${JSON.stringify(entry.focus)}).focus()`);
  } else {
    throw new Error(`unknown step ${JSON.stringify(entry)}`);
  }
}

const browser = await launch(chromePath, spec.host);
const scenarios = {};
try {
  const { cdp } = browser;
  for (const scenario of spec.scenarios) {
    // A fresh document per scenario: the query makes it a full navigation
    // (a hash-only change would stay in the same document).
    await cdp.load(`${pathToFileURL(page).href}?${scenario.id}#${scenario.id}`);
    await cdp.evaluate("window.__panels.settle()");
    if ((await cdp.evaluate("window.__panels.scenario")) !== scenario.id) {
      throw new Error(`the page did not load ${scenario.id}`);
    }
    const snapshots = [await cdp.evaluate("window.__panels.snapshot()")];
    const pressed = { left: false };
    for (const entry of scenario.steps) {
      await step(cdp, entry, pressed);
      await cdp.evaluate("window.__panels.settle()");
      snapshots.push(await cdp.evaluate("window.__panels.snapshot()"));
    }
    scenarios[scenario.id] = snapshots;
    console.log(`${scenario.id}: ${snapshots.length} snapshots`);
  }
} finally {
  await browser.close();
}

// One snapshot per line keeps the fixture reviewable.
const comment =
  "Generated by tools/fidelity/capture.mjs from panels-scenarios.json; do not edit. " +
  "Snapshot 0 is after mount, snapshot n after step n.";
const lines = Object.entries(scenarios).map(
  ([id, snapshots]) =>
    `    ${JSON.stringify(id)}: [\n${snapshots.map((s) => `      ${JSON.stringify(s)}`).join(",\n")}\n    ]`,
);
writeFileSync(
  outputPath,
  [
    "{",
    `  "comment": ${JSON.stringify(comment)},`,
    `  "chromium": ${JSON.stringify(browser.version)},`,
    `  "packages": ${JSON.stringify(generator)},`,
    '  "scenarios": {',
    lines.join(",\n"),
    "  }",
    "}",
    "",
  ].join("\n"),
);
console.log(`${browser.version}; ${generator}`);
